import Foundation

/// Геометрия щётки под графиком — В ПУНКТАХ.
///
/// Перенесено из EUC Logger дословно (`Sources/Core/BrushLayout.swift`) —
/// вместе с комментариями: они и есть документация выстраданных инвариантов.
///
/// Долей ширины эта геометрия быть НЕ МОЖЕТ, и это не вкусовщина: палец не
/// масштабируется вместе с вьюхой. Допуск захвата долей (0,045 полосы) давал
/// цель 31 pt на узкой полосе и 45–53 pt на широкой — один код и две РАЗНЫЕ
/// эргономики, причём первая мимо HIG (44 pt). Это ровно та ошибка, что уже
/// оплачена в `ChartWindow.minSpan`: доля притворялась физической величиной.
///
/// Вторая обязанность структуры — держать отрисовку и попадание НА ОДНОЙ
/// арифметике. Нарисованный бегунок шире настоящего окна (см. `minThumb`), и
/// если бы «где рисуем» и «куда попадаем» считались порознь, они разъехались
/// бы на первой же правке: ручка на экране в одном месте, хватается в другом.
struct BrushLayout {

    /// ВИДИМАЯ ширина ручки.
    ///
    /// Ручка — капсула, а не линия в 2 pt: за линию не «хватаются», она не
    /// читается как орган управления. 14 pt хватает, чтобы внутри поместилась
    /// насечка — единственный общепонятный знак «за это тянут».
    static let handle: Double = 14

    /// Цель для пальца (HIG). Видимую ширину она превышает втрое, и так и
    /// задумано: видимое и хватаемое обязаны быть разведены, иначе одно из
    /// двух врёт — ручка либо промахивается мимо пальца, либо закрывает
    /// полграфика.
    static let grab: Double = 44

    /// Минимальная НАРИСОВАННАЯ ширина бегунка — как у ползунка скроллбара.
    ///
    /// Узкое окно тут не краевой случай, а НОРМА экрана: окно «7 дней» на
    /// двухлетней истории — это около одного процента полосы, единицы пунктов.
    /// Без этого пола две зоны захвата по 44 pt сидели бы одна на другой, и
    /// правый край был бы недостижим В ПРИНЦИПЕ (проверка левого стоит первой
    /// — так и было).
    ///
    /// Про ширину окна бегунок при этом врать не имеет права: настоящие края
    /// рисуются внутри него отдельно (`trueLo`/`trueHi`, `widened`).
    static let minThumb: Double = 48

    /// Насколько зона захвата ручки уходит ВНУТРЬ бегунка.
    ///
    /// Ровно до края её видимой капсулы и ни пунктом дальше — требование
    /// владельца: «область, за которую могу схватиться, должна быть в границах
    /// ползунков, потому что я хочу взяться за центр полосы и двигать её».
    /// Раньше ручка забирала внутрь по 22 pt (половину `grab`), и у бегунка
    /// уже 112 pt середины не оставалось вовсе — окно нельзя было перетащить
    /// целиком, хотя пальцем в него человек попадал.
    ///
    /// Наружу зона по-прежнему широкая (`grab`/2): там она никому не мешает и
    /// именно она позволяет поймать край, не целясь в него.
    static let inwardGrab: Double = handle / 2

    /// Что поймал палец. Порядок проверок роли не играет: зоны разведены ПО
    /// ПОСТРОЕНИЮ (см. `hit`), а не порядком `if`-ов.
    enum Zone: Equatable {
        case left, right, pan
    }

    /// Ширина полосы щётки, pt.
    let width: Double
    /// НАРИСОВАННЫЙ левый край бегунка, pt.
    let lo: Double
    /// НАРИСОВАННЫЙ правый край бегунка, pt.
    let hi: Double
    /// Настоящий левый край окна, pt.
    let trueLo: Double
    /// Настоящий правый край окна, pt.
    let trueHi: Double

    /// Бегунок ШИРЕ настоящего окна — значит он про ширину окна врёт, и
    /// настоящие края обязаны быть нарисованы внутри него отдельно.
    var widened: Bool { (hi - lo) - (trueHi - trueLo) > 0.01 }

    /// Есть ли у бегунка середина, за которую можно тащить окно целиком.
    /// Середина у бегунка есть ВСЕГДА, пока между капсулами остаётся место.
    /// При минимальной ширине (`minThumb` 48) это 34 pt — палец попадает.
    var hasPan: Bool { hi - lo > 2 * Self.inwardGrab }

    /// Центр НАРИСОВАННОЙ капсулы: у края полосы она вжимается внутрь целиком,
    /// а не выезжает половиной за край.
    ///
    /// Этот зажим обязан жить ЗДЕСЬ, а не в рисовании. Пока он был снаружи,
    /// «где ручка» и «куда попадаешь» считались порознь и разъехались ровно
    /// так, как обещает доккомментарий структуры: на окне «Всё» капсула
    /// нарисована в [0…14], а зона левого края кончалась на 7 pt, и вторая
    /// половина видимой ручки (вместе с одной из двух насечек) была мёртвой.
    private func capsuleCenter(_ x: Double) -> Double {
        let h = Self.handle / 2
        return Swift.min(Swift.max(x, h), Swift.max(h, width - h))
    }

    /// Центры нарисованных капсул — по ним и рисуют, и попадают.
    var capLo: Double { capsuleCenter(lo) }
    var capHi: Double { capsuleCenter(hi) }

    init(window: ChartWindow, width: Double) {
        // Ноль и нечисло — обычная жизнь `GeometryReader` на первом кадре, а не
        // ошибка вызывающего: на ширину делят, поэтому чиним молча.
        let w = Swift.max(width.isFinite ? width : 1, 1)
        let a0 = Swift.min(Swift.max(window.w0, 0), 1) * w
        let b0 = Swift.min(Swift.max(window.w1, 0), 1) * w
        var a = a0
        var b = b0
        // На совсем узкой полосе бегунок не может быть шире её самой.
        let thumb = Swift.min(Self.minThumb, w)
        if b - a < thumb {
            // Раздуваем ОТ ЦЕНТРА и вдвигаем в полосу — то же правило, что у
            // самого окна: бегунок не должен прыгать к краю из-под пальца.
            let c = (a + b) / 2
            a = c - thumb / 2
            b = c + thumb / 2
            if a < 0 { b -= a; a = 0 }
            if b > w { a -= (b - w); b = w }
            a = Swift.max(a, 0)
            b = Swift.min(b, w)
        }
        self.width = w
        self.lo = a
        self.hi = b
        self.trueLo = a0
        self.trueHi = b0
    }

    /// Что поймал палец в точке `x` (пункты от левого края полосы).
    ///
    /// `nil` — мимо бегунка: это не «ничего не делать», а тап-перенос окна под
    /// палец (см. `ChartWindow.begin`).
    ///
    /// Зоны НЕ ПЕРЕКРЫВАЮТСЯ и не оставляют дыр ПО ПОСТРОЕНИЮ, а не порядком
    /// проверок. Раньше их разводил именно порядок («левый первым»), и на узком
    /// окне вся зона доставалась левому краю — правый было не ухватить вовсе.
    ///
    /// Внутрь ручка забирает только свою капсулу (`inwardGrab`), наружу —
    /// половину `grab`. Поэтому середина есть при любой рабочей ширине, а
    /// щели между зонами не возникает по построению: они смыкаются ровно на
    /// краях капсул. Вырожденный случай (бегунок уже двух капсул) делится
    /// по центру — там середины нет физически.
    func hit(_ x: Double) -> Zone? {
        guard x.isFinite else { return nil }
        let half = Self.grab / 2
        let center = (lo + hi) / 2
        // Внутрь ручка забирает свою НАРИСОВАННУЮ капсулу, поэтому границы
        // считаются от `capLo`/`capHi`. Зажим центром нужен на вырожденном
        // бегунке: там середины нет физически, и зоны не должны пересечься.
        let leftHi = hasPan ? Swift.min(capLo + Self.inwardGrab, center) : center
        let rightLo = hasPan ? Swift.max(capHi - Self.inwardGrab, center) : center
        if x >= lo - half, x <= leftHi { return .left }
        if x >= rightLo, x <= hi + half { return .right }
        if hasPan, x > leftHi, x < rightLo { return .pan }
        return nil
    }
}
